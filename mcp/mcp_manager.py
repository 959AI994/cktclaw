"""
MCP Server Manager — lifecycle management for stdio-based MCP servers.

Starts MCP server subprocesses on demand (not at startup) and tracks
which servers are alive. The orchestrator engine queries this manager
to decide the execution hierarchy: MCP → wrapper → direct.
"""

import json
import subprocess
import threading
from pathlib import Path
from typing import Optional

from ..eda_tools.tool_detection import ToolManifest

_MCP_SERVERS_PATH = Path(__file__).parent / "mcp-servers.json"


class MCPServerHandle:
    """Tracks a running MCP server subprocess."""

    def __init__(self, name: str, proc: subprocess.Popen, config: dict):
        self.name = name
        self.proc = proc
        self.config = config

    def is_alive(self) -> bool:
        return self.proc.poll() is None

    def stop(self) -> None:
        if self.is_alive():
            try:
                self.proc.terminate()
                self.proc.wait(timeout=5)
            except Exception:
                self.proc.kill()


class MCPServerManager:
    """
    Manages a pool of MCP server processes.

    Reads server definitions from mcp-servers.json (generated by mcp_config)
    and starts/stops them on demand.
    """

    def __init__(self, config_path: Optional[Path] = None):
        self._config_path = config_path or _MCP_SERVERS_PATH
        self._servers: dict[str, dict] = {}
        self._handles: dict[str, MCPServerHandle] = {}
        self._lock = threading.Lock()
        self._load_config()

    def _load_config(self) -> None:
        if self._config_path.is_file():
            try:
                self._servers = json.loads(self._config_path.read_text())
            except (json.JSONDecodeError, OSError):
                self._servers = {}

    def reload_config(self) -> None:
        with self._lock:
            self._load_config()

    @property
    def available_servers(self) -> list[str]:
        return list(self._servers.keys())

    def is_configured(self, server_name: str) -> bool:
        return server_name in self._servers

    def is_running(self, server_name: str) -> bool:
        with self._lock:
            h = self._handles.get(server_name)
            return h is not None and h.is_alive()

    def start_server(self, server_name: str) -> bool:
        """Start an MCP server. Returns True on success."""
        with self._lock:
            if server_name in self._handles and self._handles[server_name].is_alive():
                return True

            cfg = self._servers.get(server_name)
            if not cfg:
                return False

            command = cfg.get("command", "")
            args = cfg.get("args", [])
            env_overrides = cfg.get("env", {})

            import os
            env = dict(os.environ)
            env.update(env_overrides)

            try:
                proc = subprocess.Popen(
                    [command] + args,
                    stdin=subprocess.PIPE,
                    stdout=subprocess.PIPE,
                    stderr=subprocess.PIPE,
                    text=True,
                    env=env,
                )
                self._handles[server_name] = MCPServerHandle(server_name, proc, cfg)
                return True
            except (FileNotFoundError, OSError):
                return False

    def stop_server(self, server_name: str) -> None:
        with self._lock:
            h = self._handles.pop(server_name, None)
            if h:
                h.stop()

    def stop_all(self) -> None:
        with self._lock:
            for h in self._handles.values():
                h.stop()
            self._handles.clear()

    def get_preference_order(
        self, tool_name: str, manifest: ToolManifest
    ) -> list[str]:
        """
        Return the execution preference for *tool_name*: ``["mcp", "wrapper", "direct"]``
        filtered to what is actually available.

        Orchestrator MCP Preference hierarchy:
          1. MCP server (if configured)
          2. Wrapper script (if wrapper exists and is executable)
          3. Direct execution (if tool binary found on PATH)
        """
        order: list[str] = []

        if self.is_configured(tool_name):
            order.append("mcp")

        wrapper_key = f"wrap-{tool_name}.sh"
        # Special cases where wrapper name differs from tool name
        _WRAPPER_ALIASES = {
            "opensta": "wrap-opensta.sh",
            "verilator": "wrap-verilator-sim.sh",
            "symbiyosys": "wrap-symbiflow.sh",
        }
        wrapper_key = _WRAPPER_ALIASES.get(tool_name, wrapper_key)
        if manifest.wrappers.get(wrapper_key, False):
            order.append("wrapper")

        if manifest.is_tool_available(tool_name):
            order.append("direct")

        return order
